// Runs the VLM baseline: renders labels with known ground truth in the browser, asks the model, writes src/baseline.ts.
import { chromium } from 'playwright'
import fs from 'fs'
const b = await chromium.launch()
const p = await b.newPage(); await p.goto('http://localhost:4400/baseline-gen.html')
await p.waitForFunction(() => document.getElementById('o').textContent === 'DONE', null, { timeout: 120000 })
const items = await p.evaluate(() => window.__out); await b.close()
const { PROMPT } = await import('../api/baseline.js')
const expected = (d) => (d <= 2 ? 'DISCARD' : 'USE')
const rows = []
for (const it of items) {
  const r = await fetch('https://api.featherless.ai/v1/chat/completions', { method: 'POST', headers: { authorization: `Bearer ${process.env.FEATHERLESS_API_KEY}`, 'content-type': 'application/json' },
    body: JSON.stringify({ model: 'Qwen/Qwen3-VL-30B-A3B-Instruct', temperature: 0, max_tokens: 40, messages: [{ role: 'user', content: [{ type: 'image_url', image_url: { url: it.photo } }, { type: 'text', text: PROMPT }] }] }) })
  const j = await r.json(); const ai = (j?.choices?.[0]?.message?.content || JSON.stringify(j).slice(0, 80)).trim().replace(/\s+/g, ' ')
  const aiCall = /DISCARD/i.test(ai) ? 'DISCARD' : /USE/i.test(ai) ? 'USE' : '?'
  const vsCall = it.vs === 'USE FIRST' ? 'USE' : it.vs
  rows.push({ truth: it.delta, expected: expected(it.delta), ai, aiCorrect: aiCall === expected(it.delta), vs: `${it.vs} (${it.vsDelta?.toFixed(1)})`, vsCorrect: vsCall === expected(it.delta) })
  fs.writeFileSync('/tmp/' + `label_${it.delta}.png`, Buffer.from(it.photo.split(',')[1], 'base64'))
  console.log(it.delta, '|', ai, '|', it.vs, it.vsDelta?.toFixed(1))
}
const aiOk = rows.filter((r) => r.aiCorrect).length, vsOk = rows.filter((r) => r.vsCorrect).length
const unsafeAI = rows.filter((r) => r.expected === 'DISCARD' && !r.aiCorrect).length
const summary = `Same ${rows.length} labels, temperature 0, run ${new Date().toISOString().slice(0, 10)}. Qwen3-VL-30B: ${aiOk}/${rows.length} correct, ${unsafeAI} unsafe (a discard label called usable). VialSight: ${vsOk}/${rows.length} correct.`
fs.writeFileSync('src/baseline.ts', `// Generated by scripts/baseline.mjs: the same labels sent to a vision-language model.\nexport const BASELINE = ${JSON.stringify({ rows, summary }, null, 2)}\n`)
console.log(summary)
